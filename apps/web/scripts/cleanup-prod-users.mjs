#!/usr/bin/env node
import fs from 'fs'
import path from 'path'
import { createClient } from '@supabase/supabase-js'

const argv = Object.fromEntries(process.argv.slice(2).map(a => {
  const [k, v] = a.split('=')
  return [k.replace(/^--/, ''), v ?? true]
}))

const OUT = argv.output || 'reports/cleanup.sql'
const CONFIRM = argv.confirm === 'true' || argv.confirm === true

const SUPABASE_URL = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL
const SUPABASE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SECRET_KEY

if (!SUPABASE_URL || !SUPABASE_KEY) {
  console.error('Faltan variables de entorno: SUPABASE_URL y SUPABASE_SERVICE_ROLE_KEY')
  process.exit(1)
}

const supabase = createClient(SUPABASE_URL, SUPABASE_KEY, {
  auth: { persistSession: false, autoRefreshToken: false }
})

async function gatherAllUserIds() {
  let page = 1
  const ids = []
  while (true) {
    const { data, error } = await supabase.auth.admin.listUsers({ page, perPage: 100 })
    if (error) throw error
    if (!data || data.length === 0) break
    ids.push(...data.map(u => ({ id: u.id, email: u.email })))
    page += 1
  }
  return ids
}

function ensureOutDir(file) {
  const dir = path.dirname(file)
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true })
}

async function main() {
  console.log('Generando SQL de limpieza (DRY) ...')
  const users = await gatherAllUserIds()
  ensureOutDir(OUT)
  const lines = []
  lines.push('-- Cleanup SQL generated by cleanup-prod-users.mjs')
  lines.push('-- **DRY RUN**: statements are commented out. Review and enable before executing in production.')
  lines.push('BEGIN;')
  for (const u of users) {
    const id = u.id
    const email = u.email || ''
    lines.push(`-- User: ${id} (${email})`)
    lines.push(`-- DELETE FROM public.band_invites WHERE created_by = '${id}' OR email = '${email}';`)
    lines.push(`-- DELETE FROM public.band_memberships WHERE user_id = '${id}';`)
    lines.push(`-- DELETE FROM public.bands WHERE created_by = '${id}';`)
    lines.push(`-- DELETE FROM public.profiles WHERE id = '${id}';`)
    lines.push(`-- -- Optionally remove from auth.users (use Supabase admin API or SQL editor):`)
    lines.push(`-- -- DELETE FROM auth.users WHERE id = '${id}';`)
    lines.push('')
  }
  lines.push('COMMIT;')
  fs.writeFileSync(OUT, lines.join('\n'))
  console.log('SQL dry-run guardado en', OUT)
  if (CONFIRM) {
    const execOut = OUT.replace(/\.sql$/i, '.exec.sql')
    const execLines = []
    execLines.push('-- EXECUTABLE cleanup SQL - USE WITH CAUTION')
    execLines.push('BEGIN;')
    for (const u of users) {
      const id = u.id
      const email = u.email || ''
      execLines.push(`DELETE FROM public.band_invites WHERE created_by = '${id}' OR email = '${email}';`)
      execLines.push(`DELETE FROM public.band_memberships WHERE user_id = '${id}';`)
      execLines.push(`DELETE FROM public.bands WHERE created_by = '${id}';`)
      execLines.push(`DELETE FROM public.profiles WHERE id = '${id}';`)
      execLines.push(`-- DELETE FROM auth.users WHERE id = '${id}'; -- handle via Supabase admin API if required`)
      execLines.push('')
    }
    execLines.push('COMMIT;')
    fs.writeFileSync(execOut, execLines.join('\n'))
    console.log('SQL ejecutable guardado en', execOut)
  }
}

main().catch(err => {
  console.error('Error:', err.message || err)
  process.exit(1)
})
